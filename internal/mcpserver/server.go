const ProtocolVersion = "2025-03-26"

// Session holds the scoped state for one active gateway run exposed via MCP.
type Session struct {
	RunID            string
	Token            string
	RunCtx           tools.RunContext
	ServerTools      []string
	ClientTools      []executor.ToolDefinition
	OnClientToolCall func(call executor.ToolCall)

	mu              sync.Mutex
	capturedCalls   []executor.ToolCall
	generatedFiles  []executor.GeneratedFileRef
	clientToolIndex map[string]executor.ToolDefinition
	serverAllowSet  map[string]bool
	allowAllServer  bool
}

// CapturedClientCalls returns a copy of client-defined tool calls captured during the run.
func (s *Session) CapturedClientCalls() []executor.ToolCall {
	s.mu.Lock()
	defer s.mu.Unlock()
	out := make([]executor.ToolCall, len(s.capturedCalls))
	copy(out, s.capturedCalls)
	return out
}

// GeneratedFiles returns all files generated by server tools during the run.
func (s *Session) GeneratedFiles() []executor.GeneratedFileRef {
	s.mu.Lock()
	defer s.mu.Unlock()
	out := make([]executor.GeneratedFileRef, len(s.generatedFiles))
	copy(out, s.generatedFiles)
	return out
}

func (s *Session) recordGeneratedFile(ref executor.GeneratedFileRef) {
	s.mu.Lock()
	s.generatedFiles = append(s.generatedFiles, ref)
	s.mu.Unlock()
}

// Server serves per-run scoped MCP JSON-RPC 2.0 requests at POST /internal/mcp/{run_id}.
type Server struct {
	registry *tools.Registry
	mu       sync.RWMutex
	sessions map[string]*Session
}

func NewServer(registry *tools.Registry) *Server {
	return &Server{
		registry: registry,
		sessions: make(map[string]*Session),
	}
}

// RegisterSession creates a new ephemeral per-run MCP session and returns it (caller must UnregisterSession on run completion).
func (s *Server) RegisterSession(runID string, runCtx tools.RunContext, serverTools []string, clientTools []executor.ToolDefinition, onClientCall func(executor.ToolCall)) *Session {
	tok := randomHex(24)
	sess := &Session{
		RunID:            runID,
		Token:            tok,
		RunCtx:           runCtx,
		ServerTools:      serverTools,
		ClientTools:      clientTools,
		OnClientToolCall: onClientCall,
		clientToolIndex:  make(map[string]executor.ToolDefinition, len(clientTools)),
		serverAllowSet:   make(map[string]bool, len(serverTools)),
	}
	for _, ct := range clientTools {
		sess.clientToolIndex[ct.Name] = ct
	}
	for _, st := range serverTools {
		n := strings.TrimSpace(st)
		if n == "*" {
			sess.allowAllServer = true
		} else if n != "" {
			sess.serverAllowSet[n] = true
		}
	}
	origOnGen := runCtx.OnFileGenerated
	sess.RunCtx.OnFileGenerated = func(ref executor.GeneratedFileRef) {
		sess.recordGeneratedFile(ref)
		if origOnGen != nil {
			origOnGen(ref)
		}
	}

	s.mu.Lock()
	s.sessions[runID] = sess
	s.mu.Unlock()
	return sess
}

// UnregisterSession removes a completed run's MCP session immediately.
func (s *Server) UnregisterSession(runID string) {
	s.mu.Lock()
	delete(s.sessions, runID)
	s.mu.Unlock()
}

func (s *Server) getSession(runID string) (*Session, bool) {
	s.mu.RLock()
	defer s.mu.RUnlock()
	sess, ok := s.sessions[runID]
	return sess, ok
}

type rpcRequest struct {
	JSONRPC string          `json:"jsonrpc"`
	ID      any             `json:"id,omitempty"`
	Method  string          `json:"method"`
	Params  json.RawMessage `json:"params,omitempty"`
}

type rpcError struct {
	Code    int    `json:"code"`
	Message string `json:"message"`
}

type rpcResponse struct {
	JSONRPC string    `json:"jsonrpc"`
	ID      any       `json:"id,omitempty"`
	Result  any       `json:"result,omitempty"`
	Error   *rpcError `json:"error,omitempty"`
}

// HandleHTTP handles POST /internal/mcp/{run_id}.
func (s *Server) HandleHTTP(w http.ResponseWriter, r *http.Request) {
	runID := r.PathValue("run_id")
	sess, ok := s.getSession(runID)
	if !ok {
		http.Error(w, "unknown mcp session", http.StatusNotFound)
		return
	}

	authz := strings.TrimSpace(r.Header.Get("Authorization"))
	if !strings.HasPrefix(authz, "Bearer ") {
		http.Error(w, "missing bearer token", http.StatusUnauthorized)
		return
	}
	gotTok := strings.TrimSpace(strings.TrimPrefix(authz, "Bearer "))
	if subtle.ConstantTimeCompare([]byte(gotTok), []byte(sess.Token)) != 1 {
		http.Error(w, "invalid bearer token", http.StatusUnauthorized)
		return
	}

	raw, err := io.ReadAll(io.LimitReader(r.Body, 4*1024*1024))
	if err != nil {
		writeRPC(w, rpcResponse{JSONRPC: "2.0", Error: &rpcError{Code: -32700, Message: "read body failed"}})
		return
	}
	var req rpcRequest
	if err := json.Unmarshal(raw, &req); err != nil {
		writeRPC(w, rpcResponse{JSONRPC: "2.0", Error: &rpcError{Code: -32700, Message: "invalid JSON-RPC payload"}})
		return
	}

	switch req.Method {
	case "notifications/initialized":
		w.WriteHeader(http.StatusAccepted)
		return
	case "ping":
		writeRPC(w, rpcResponse{JSONRPC: "2.0", ID: req.ID, Result: map[string]any{}})
		return
	case "initialize":
		writeRPC(w, rpcResponse{
			JSONRPC: "2.0",
			ID:      req.ID,
			Result: map[string]any{
				"protocolVersion": ProtocolVersion,
				"serverInfo": map[string]any{
					"name":    "cli-ai-gateway-mcp",
					"version": "1.0.0",
				},
				"capabilities": map[string]any{
					"tools": map[string]any{"listChanged": false},
				},
			},
		})
		return
	case "tools/list":
		var list []map[string]any
		if s.registry != nil {
			for _, def := range s.registry.Definitions(sess.ServerTools) {
				schema := def.Parameters
				if schema == nil {
					schema = map[string]any{"type": "object", "properties": map[string]any{}}
				}
				list = append(list, map[string]any{
					"name":        def.Name,
					"description": def.Description,
					"inputSchema": schema,
				})
			}
		}
		for _, ct := range sess.ClientTools {
			schema := ct.Parameters
			if schema == nil {
				schema = map[string]any{"type": "object", "properties": map[string]any{}}
			}
			list = append(list, map[string]any{
				"name":        ct.Name,
				"description": ct.Description,
				"inputSchema": schema,
			})
		}
		if list == nil {
			list = []map[string]any{}
		}
		writeRPC(w, rpcResponse{
			JSONRPC: "2.0",
			ID:      req.ID,
			Result:  map[string]any{"tools": list},
		})
		return
	case "tools/call":
		var params struct {
			Name      string          `json:"name"`
			Arguments json.RawMessage `json:"arguments"`
		}
		if err := json.Unmarshal(req.Params, &params); err != nil || strings.TrimSpace(params.Name) == "" {
			writeRPC(w, rpcResponse{JSONRPC: "2.0", ID: req.ID, Error: &rpcError{Code: -32602, Message: "invalid tools/call params"}})
			return
		}
		if len(params.Arguments) == 0 {
			params.Arguments = json.RawMessage(`{}`)
		}

		// 1. Check client-defined OpenAI tools first (MCP Bridge capture).
		if _, isClient := sess.clientToolIndex[params.Name]; isClient {
			call := executor.ToolCall{
				ID:        "call_" + randomHex(12),
				Name:      params.Name,
				Arguments: string(params.Arguments),
			}
			sess.mu.Lock()
			sess.capturedCalls = append(sess.capturedCalls, call)
			sess.mu.Unlock()
			if sess.OnClientToolCall != nil {
				sess.OnClientToolCall(call)
			}
			writeRPC(w, rpcResponse{
				JSONRPC: "2.0",
				ID:      req.ID,
				Result: map[string]any{
					"content": []map[string]any{
						{"type": "text", "text": fmt.Sprintf("Client tool %q delegated to caller (call_id=%s). Stop and wait for caller tool result.", call.Name, call.ID)},
					},
					"isError": false,
				},
			})
			return
		}

		// 2. Check allowed server-side tools.
		if !sess.allowAllServer && !sess.serverAllowSet[params.Name] {
			writeRPC(w, rpcResponse{JSONRPC: "2.0", ID: req.ID, Error: &rpcError{Code: -32602, Message: fmt.Sprintf("tool %q is not permitted for this run", params.Name)}})
			return
		}
		if s.registry == nil {
			writeRPC(w, rpcResponse{JSONRPC: "2.0", ID: req.ID, Error: &rpcError{Code: -32603, Message: "tool registry unavailable"}})
			return
		}
		out, execErr := s.registry.Execute(r.Context(), sess.RunCtx, params.Name, params.Arguments)
		text := out.Text
		if text == "" && execErr != nil {
			text = execErr.Error()
		}
		writeRPC(w, rpcResponse{
			JSONRPC: "2.0",
			ID:      req.ID,
			Result: map[string]any{
				"content": []map[string]any{
					{"type": "text", "text": text},
				},
				"isError": execErr != nil || out.IsError,
			},
		})
		return
	default:
		writeRPC(w, rpcResponse{JSONRPC: "2.0", ID: req.ID, Error: &rpcError{Code: -32601, Message: fmt.Sprintf("method %q not found", req.Method)}})
	}
}

func writeRPC(w http.ResponseWriter, resp rpcResponse) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(http.StatusOK)
	_ = json.NewEncoder(w).Encode(resp)
}

func randomHex(n int) string {
	b := make([]byte, n)
	_, _ = rand.Read(b)
	return hex.EncodeToString(b)
}
