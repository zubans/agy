#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

MANIFEST_FILE="${WORKERS_MANIFEST:-.workers}"
COMPOSE_WORKERS_FILE="${COMPOSE_WORKERS_FILE:-compose.workers.yaml}"
MODELS_YAML_FILE="${WORKERS_MODELS_YAML:-workers.models.yaml}"

load_env() {
  if [ -f .env ]; then
    set -a
    # shellcheck disable=SC1091
    . ./.env
    set +a
  fi
}

parse_kv_args() {
  for arg in "$@"; do
    case "$arg" in
      TYPE=*) export TYPE="${arg#TYPE=}" ;;
      NAME=*) export NAME="${arg#NAME=}" ;;
      SLOT=*) export SLOT="${arg#SLOT=}" ;;
      COUNT=*) export COUNT="${arg#COUNT=}" ;;
      ACCOUNT=*) export ACCOUNT="${arg#ACCOUNT=}" ;;
      PURGE_VOLUME=*) export PURGE_VOLUME="${arg#PURGE_VOLUME=}" ;;
    esac
  done
}

compose_cmd() {
  if [ -f "$COMPOSE_WORKERS_FILE" ]; then
    docker compose -f compose.yaml -f "$COMPOSE_WORKERS_FILE" "$@"
  else
    docker compose -f compose.yaml "$@"
  fi
}

normalize_type() {
  case "${1:-}" in
    agy|antigravity) echo "agy" ;;
    codex) echo "codex" ;;
    claude) echo "claude" ;;
    gemini) echo "gemini" ;;
    *)
      echo "Unsupported agent type '${1:-}'. Expected: claude | codex | gemini | agy" >&2
      return 1
      ;;
  esac
}

provider_for_type() {
  case "$1" in
    agy) echo "antigravity" ;;
    *) echo "$1" ;;
  esac
}

image_target_for_type() {
  echo "worker-$1"
}

validate_name() {
  local name="$1"
  if [[ ! "$name" =~ ^[a-z][a-z0-9-]{0,62}$ ]]; then
    echo "Invalid container/model name '$name'. Use lowercase letters, digits, hyphens (start with letter, <=63 chars)." >&2
    return 1
  fi
}

volume_for_name() {
  echo "${1//-/_}_home"
}

worker_exists() {
  local target="$1"
  [ -f "$MANIFEST_FILE" ] && awk -v t="$target" '!/^[[:space:]]*(#|$)/ && $1 == t {found=1; exit} END {exit !found}' "$MANIFEST_FILE"
}

type_for_worker() {
  local target="$1"
  [ -f "$MANIFEST_FILE" ] || return 1
  awk -v t="$target" '!/^[[:space:]]*(#|$)/ && $1 == t {print $2; found=1; exit} END {exit !found}' "$MANIFEST_FILE"
}

next_slot_name() {
  local wtype="$1"
  local n=1
  while worker_exists "${wtype}-${n}"; do
    n=$((n + 1))
  done
  echo "${wtype}-${n}"
}

list_entries() {
  [ -f "$MANIFEST_FILE" ] || return 0
  awk '!/^[[:space:]]*(#|$)/ {print $1, $2}' "$MANIFEST_FILE"
}

render_files() {
  local entries=()
  while IFS= read -r line; do
    [ -n "$line" ] && entries+=("$line")
  done < <(list_entries)

  # Generate workers.models.yaml consumed by gateway (GATEWAY_WORKERS_CONFIG).
  {
    echo "# Auto-generated by scripts/workers.sh from ${MANIFEST_FILE}. Edit via 'make agent-add' / 'make agent-rm'."
    if [ "${#entries[@]}" -eq 0 ]; then
      echo "models: []"
    else
      echo "models:"
      for entry in "${entries[@]}"; do
        local name="${entry%% *}"
        local wtype="${entry##* }"
        local prov
        prov="$(provider_for_type "$wtype")"
        cat <<EOF
  - id: ${name}
    provider: ${prov}
    worker_url: http://${name}:9090
    timeout_seconds: 600
    max_concurrent: 4
    fs_access: workspace-read
    public: false
EOF
      done
    fi
  } > "$MODELS_YAML_FILE"

  # Generate compose.workers.yaml merged alongside compose.yaml.
  {
    echo "# Auto-generated by scripts/workers.sh from ${MANIFEST_FILE}. Edit via 'make agent-add' / 'make agent-rm'."
    if [ "${#entries[@]}" -eq 0 ]; then
      echo "services: {}"
      return 0
    fi

    cat <<EOF
services:
  gateway:
    depends_on:
EOF
    for entry in "${entries[@]}"; do
      local name="${entry%% *}"
      echo "      - ${name}"
    done
    cat <<EOF
    environment:
      GATEWAY_WORKERS_CONFIG: /etc/cli-ai-gateway/workers.yaml
    volumes:
      - ./${MODELS_YAML_FILE}:/etc/cli-ai-gateway/workers.yaml:ro
EOF

    for entry in "${entries[@]}"; do
      local name="${entry%% *}"
      local wtype="${entry##* }"
      local target
      target="$(image_target_for_type "$wtype")"
      local vol
      vol="$(volume_for_name "$name")"
      cat <<EOF

  ${name}:
    build:
      context: .
      dockerfile: Dockerfile
      target: ${target}
    image: cli-ai-worker-${wtype}:local
    restart: unless-stopped
    user: "10001:10001"
    security_opt:
      - no-new-privileges:true
    cap_drop:
      - ALL
    read_only: true
    tmpfs:
      - /tmp:rw,nosuid,nodev,size=512m
    expose:
      - "9090"
    cpus: "\${WORKER_CPUS:-1.0}"
    mem_limit: \${WORKER_MEM_LIMIT:-1g}
    pids_limit: 128
    environment:
      GATEWAY_WORKER_TOKEN: "\${GATEWAY_WORKER_TOKEN:-dev-worker-token-change-me}"
      GATEWAY_LOG_LEVEL: "\${GATEWAY_LOG_LEVEL:-info}"
EOF
      if [ "$wtype" = "gemini" ]; then
        echo '      NO_BROWSER: "true"'
      fi
      cat <<EOF
    volumes:
      - ${vol}:/var/lib/cli-gateway/home
EOF
    done

    echo ""
    echo "volumes:"
    for entry in "${entries[@]}"; do
      local name="${entry%% *}"
      local vol
      vol="$(volume_for_name "$name")"
      echo "  ${vol}:"
    done
  } > "$COMPOSE_WORKERS_FILE"
}

validate_uint() {
  local val="$1"
  local label="$2"
  if [[ ! "$val" =~ ^[0-9]+$ ]]; then
    echo "Invalid integer for $label: '$val'" >&2
    exit 1
  fi
}

cmd_init() {
  local req_claude="${CLAUDE_COUNT:-}"
  local req_codex="${CODEX_COUNT:-}"
  local req_gemini="${GEMINI_COUNT:-}"
  local req_agy="${AGY_COUNT:-}"
  load_env
  local claude_cnt="${req_claude:-${CLAUDE_COUNT:-1}}"
  local codex_cnt="${req_codex:-${CODEX_COUNT:-1}}"
  local gemini_cnt="${req_gemini:-${GEMINI_COUNT:-1}}"
  local agy_cnt="${req_agy:-${AGY_COUNT:-3}}"

  validate_uint "$claude_cnt" "CLAUDE_COUNT"
  validate_uint "$codex_cnt" "CODEX_COUNT"
  validate_uint "$gemini_cnt" "GEMINI_COUNT"
  validate_uint "$agy_cnt" "AGY_COUNT"

  if [ ! -f "$MANIFEST_FILE" ]; then
    {
      echo "# Active CLI worker containers (<name> <claude|codex|gemini|agy>)"
      local i
      for ((i = 1; i <= claude_cnt; i++)); do echo "claude-$i claude"; done
      for ((i = 1; i <= codex_cnt; i++)); do echo "codex-$i codex"; done
      for ((i = 1; i <= gemini_cnt; i++)); do echo "gemini-$i gemini"; done
      for ((i = 1; i <= agy_cnt; i++)); do echo "agy-$i agy"; done
    } > "$MANIFEST_FILE"
    echo "Initialized $MANIFEST_FILE (claude=$claude_cnt, codex=$codex_cnt, gemini=$gemini_cnt, agy=$agy_cnt)"
  fi

  render_files
}

gateway_api_url() {
  local host="${GATEWAY_BIND_HOST:-127.0.0.1}"
  local port="${GATEWAY_PORT:-7070}"
  if [ "$host" = "0.0.0.0" ] || [ "$host" = "::" ] || [ -z "$host" ]; then
    host="127.0.0.1"
  fi
  echo "http://${host}:${port}"
}

register_live_if_running() {
  local name="$1"
  local wtype="$2"
  local url
  url="$(gateway_api_url)"
  curl -fsS "${url}/health" >/dev/null 2>&1 || return 0

  local prov
  prov="$(provider_for_type "$wtype")"
  local tok="${GATEWAY_ADMIN_TOKEN:-gw-admin-change-me}"
  local status
  status=$(curl -s -o /dev/null -w '%{http_code}' -X POST "${url}/admin/api/models" \
    -H "Authorization: Bearer ${tok}" \
    -H "Content-Type: application/json" \
    -d "{\"id\":\"${name}\",\"provider\":\"${prov}\",\"worker_url\":\"http://${name}:9090\",\"public\":false}" || true)
  if [ "$status" = "201" ]; then
    echo "Registered '${name}' in running gateway immediately (zero downtime)"
  elif [ "$status" = "409" ]; then
    echo "Gateway already knows model '${name}'"
  else
    echo "Note: gateway live registration returned HTTP ${status}; run 'make restart SERVICE=gateway' if needed"
  fi
}

cmd_add() {
  load_env
  local raw_type="${TYPE:-${1:-}}"
  if [ -z "$raw_type" ]; then
    echo "Usage: make agent-add TYPE=agy|codex|claude|gemini [NAME=...] [SLOT=...] [COUNT=1]" >&2
    exit 1
  fi
  local wtype
  wtype="$(normalize_type "$raw_type")"

  local count="${COUNT:-1}"
  validate_uint "$count" "COUNT"
  if [ "$count" -lt 1 ]; then
    echo "COUNT must be >= 1" >&2
    exit 1
  fi

  local custom_name="${NAME:-}"
  local custom_slot="${SLOT:-}"
  if [ "$count" -gt 1 ] && { [ -n "$custom_name" ] || [ -n "$custom_slot" ]; }; then
    echo "NAME and SLOT cannot be combined with COUNT > 1" >&2
    exit 1
  fi

  [ -f "$MANIFEST_FILE" ] || cmd_init

  local added=()
  local i name
  for ((i = 1; i <= count; i++)); do
    if [ -n "$custom_name" ]; then
      name="$custom_name"
    elif [ -n "$custom_slot" ]; then
      name="${wtype}-${custom_slot}"
    else
      name="$(next_slot_name "$wtype")"
    fi
    validate_name "$name"
    if worker_exists "$name"; then
      echo "Agent container '$name' already exists in $MANIFEST_FILE" >&2
      exit 1
    fi
    echo "$name $wtype" >> "$MANIFEST_FILE"
    added+=("$name")
  done

  render_files
  echo "Added container(s): ${added[*]}"

  if [ "${SKIP_DOCKER:-0}" != "1" ]; then
    compose_cmd up -d --build "${added[@]}"
    for name in "${added[@]}"; do
      register_live_if_running "$name" "$wtype"
    done
  fi

  echo "Next: authenticate each new container:"
  for name in "${added[@]}"; do
    echo "  make agent-login NAME=${name}"
  done
}

cmd_rm() {
  load_env
  local name="${NAME:-${1:-}}"
  if [ -z "$name" ]; then
    echo "Usage: make agent-rm NAME=<container> [PURGE_VOLUME=1]" >&2
    exit 1
  fi
  if ! worker_exists "$name"; then
    echo "Agent container '$name' not found in $MANIFEST_FILE" >&2
    exit 1
  fi

  local tmp
  tmp="$(mktemp)"
  awk -v t="$name" '($1 == t && !/^[[:space:]]*(#|$)/) {next} {print}' "$MANIFEST_FILE" > "$tmp"
  mv "$tmp" "$MANIFEST_FILE"

  if [ "${SKIP_DOCKER:-0}" != "1" ]; then
    compose_cmd rm -sf "$name" || true
  fi
  render_files

  if [ "${SKIP_DOCKER:-0}" != "1" ]; then
    local url status tok
    url="$(gateway_api_url)"
    tok="${GATEWAY_ADMIN_TOKEN:-gw-admin-change-me}"
    if curl -fsS "${url}/health" >/dev/null 2>&1; then
      status=$(curl -s -o /dev/null -w '%{http_code}' -X DELETE "${url}/admin/api/models/${name}" \
        -H "Authorization: Bearer ${tok}" || true)
      if [ "$status" != "200" ]; then
        echo "Refreshing gateway container to drop removed static worker '${name}'..."
        compose_cmd up -d --force-recreate --no-deps gateway
      fi
    fi

    if [ "${PURGE_VOLUME:-0}" = "1" ]; then
      local vol
      vol="$(volume_for_name "$name")"
      local full_vol
      full_vol="$(compose_cmd config --format json 2>/dev/null | awk -v v="$vol" '"volumes" {print}' || true)"
      docker volume rm -f "$(basename "$ROOT_DIR")_${vol}" >/dev/null 2>&1 || true
      echo "Removed auth volume for '${name}' (if present)"
    else
      echo "Kept persistent auth volume '$(volume_for_name "$name")' (pass PURGE_VOLUME=1 to remove it)."
    fi
  fi
}

cmd_login() {
  load_env
  local name="${NAME:-}"
  local raw_type="${TYPE:-}"
  local account="${ACCOUNT:-1}"

  local wtype=""
  if [ -n "$raw_type" ]; then
    wtype="$(normalize_type "$raw_type")"
  fi

  if [ -z "$name" ]; then
    if [ -z "$wtype" ]; then
      echo "Usage: make agent-login NAME=<container>  OR  make <claude|codex|gemini|agy>-login [ACCOUNT=1]" >&2
      exit 1
    fi
    name="${wtype}-${account}"
  fi

  if [ -z "$wtype" ]; then
    wtype="$(type_for_worker "$name" || true)"
  fi
  if [ -z "$wtype" ]; then
    case "$name" in
      claude|claude-*) wtype="claude" ;;
      codex|codex-*) wtype="codex" ;;
      gemini|gemini-*) wtype="gemini" ;;
      agy|agy-*|antigravity-*) wtype="agy" ;;
    esac
  fi

  if ! worker_exists "$name"; then
    echo "Container '$name' is not in $MANIFEST_FILE. Available agents:" >&2
    cmd_ls >&2 || true
    exit 1
  fi

  if [ -z "$(compose_cmd ps -q "$name" 2>/dev/null || true)" ]; then
    echo "Container '$name' is not running. Starting it now..."
    compose_cmd up -d "$name"
  fi

  echo "Starting interactive ${wtype} login inside container '${name}'..."
  case "$wtype" in
    claude)
      compose_cmd exec -it "$name" claude auth login
      ;;
    codex)
      compose_cmd exec -it "$name" codex login --device-auth
      ;;
    gemini)
      compose_cmd exec -it -e NO_BROWSER=true "$name" gemini
      ;;
    agy)
      compose_cmd exec -it "$name" agy
      ;;
    *)
      echo "Cannot determine CLI command for '${name}'" >&2
      exit 1
      ;;
  esac
}

cmd_ls() {
  if [ ! -f "$MANIFEST_FILE" ]; then
    echo "No $MANIFEST_FILE yet. Run 'make init' first."
    return 0
  fi
  printf "%-18s %-13s %-26s %s\n" "CONTAINER" "PROVIDER" "WORKER_URL" "VOLUME"
  while IFS= read -r entry; do
    [ -n "$entry" ] || continue
    local name="${entry%% *}"
    local wtype="${entry##* }"
    local prov
    prov="$(provider_for_type "$wtype")"
    local vol
    vol="$(volume_for_name "$name")"
    printf "%-18s %-13s %-26s %s\n" "$name" "$prov" "http://${name}:9090" "$vol"
  done < <(list_entries)
}

cmd="${1:-help}"
shift || true
parse_kv_args "$@"

case "$cmd" in
  init) cmd_init "$@" ;;
  render) render_files ;;
  add) cmd_add "${1:-}" ;;
  rm) cmd_rm "${1:-}" ;;
  login) cmd_login "$@" ;;
  ls) cmd_ls "$@" ;;
  *)
    echo "Usage: $0 {init|render|add|rm|login|ls}" >&2
    exit 1
    ;;
esac
